"""In-process dataset store for uploaded telemetry. Threat-model.md controls
applied here: server-generated storage path (never the client filename),
hard size cap, streaming-safe write, typed errors instead of crashes.

Demo dataset ("demo") = the synthetic validation dataset already generated by
scripts/generate_synthetic_dataset.py, so the API is usable without an upload.
"""
from __future__ import annotations

import uuid
from pathlib import Path

import pandas as pd

from prevail.preprocessing.clean import clean_packets, load_packets
from prevail.states.builder import build_states

MAX_UPLOAD_BYTES = 200 * 1024 * 1024  # 200 MB hard cap (threat-model.md: oversized-upload DoS)
UPLOAD_DIR = Path(__file__).resolve().parents[3] / "data" / "uploads"
ROOT = Path(__file__).resolve().parents[3]


class IngestionError(Exception):
    pass


class DatasetStore:
    def __init__(self):
        self._datasets: dict[str, dict] = {}
        UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
        self._load_demo_dataset()

    def _load_demo_dataset(self) -> None:
        packets_path = ROOT / "data" / "raw" / "synthetic_packets.csv"
        states_path = ROOT / "data" / "processed" / "states_w5s.parquet"
        if not (packets_path.exists() and states_path.exists()):
            return
        self._datasets["demo"] = {
            "packets": pd.read_csv(packets_path),
            "states": pd.read_parquet(states_path),
            "window_size_s": 5.0,
            "source": "synthetic validation dataset (see DECISIONS.md D-003)",
        }

    def ingest_bytes(self, raw_bytes: bytes, window_size_s: float = 5.0) -> str:
        if len(raw_bytes) > MAX_UPLOAD_BYTES:
            raise IngestionError(f"Upload exceeds max size of {MAX_UPLOAD_BYTES} bytes")

        dataset_id = str(uuid.uuid4())
        # Server-generated filename -- never derived from client input.
        stored_path = UPLOAD_DIR / f"{dataset_id}.csv"
        stored_path.write_bytes(raw_bytes)

        try:
            raw = load_packets(str(stored_path))
        except Exception as e:
            raise IngestionError(f"Could not parse uploaded telemetry: {e}") from e

        packets, quality_report = clean_packets(raw)
        if len(packets) == 0:
            raise IngestionError("Uploaded telemetry contained no valid rows after cleaning")

        states = build_states(packets, window_size_s=window_size_s)
        self._datasets[dataset_id] = {
            "packets": packets,
            "states": states,
            "window_size_s": window_size_s,
            "source": "user upload",
            "quality_report": quality_report.as_dict(),
        }
        return dataset_id

    def get(self, dataset_id: str) -> dict:
        if dataset_id not in self._datasets:
            raise KeyError(dataset_id)
        return self._datasets[dataset_id]

    def scenario_ids(self, dataset_id: str) -> list[str]:
        return sorted(self.get(dataset_id)["states"]["scenario_id"].unique().tolist())
